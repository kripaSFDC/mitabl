     *
     * @param  mixed  $notifiable
     * @return \Illuminate\Notifications\Messages\MailMessage
     */

    public function toDatabase()
    {
        $data =  [
            'type' => $this->type,
            'order_id' => $this->order->id,
            'message'=> $this->msg,
        ];
        return $data;

